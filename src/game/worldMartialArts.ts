const MARTIAL_ART_BY_ID = new Map<string, MartialArtDefinition>(
  WORLD_MARTIAL_ARTS.map((item) => [item.id, item])
);

/** Returns the martial art metadata (country, animal, aura, weapon, ultimate) for a fighter id, if defined. */
export function getMartialArtMeta(characterId: string): MartialArtDefinition | undefined {
  return MARTIAL_ART_BY_ID.get(characterId);
}

/** Returns all world martial arts belonging to a category (or all entries for 'all'). */
export function getWorldMartialArtsByCategory(category: MartialArtCategoryId): MartialArtDefinition[] {
  if (category === 'all') {
    return WORLD_MARTIAL_ARTS;
  }

  return WORLD_MARTIAL_ARTS.filter((art) => art.categories.includes(category));
}
